import type { Model, ModelSchema } from './model'
import type { Timestamps, TimestampNamesOf, TimestampsCheck, TimestampsOption } from './timestamps'
import type {
  Abortable,
  AggregateOptions,
  AnyBulkWriteOperation,
  Collection,
  Db,
  Document,
  ModifyResult,
  WithId
} from 'mongodb'
import type * as core from 'zod/v4/core'

import { z } from 'zod'

import { checkFieldNames } from './check-field-names'
import { ModelCursor } from './model-cursor'
import { ModelFindCursor } from './model-find-cursor'
import { parseDocument } from './parse-document'
import { parseUpdate } from './parse-update'
import { schemaAt } from './schema-at'
import { stampDocument, stampUpdate, timestampsOf } from './timestamps'
import { filterEqualities } from './upsert'

/** The options of `mongozod()`. */
export interface MongozodOptions<S extends ModelSchema, T extends TimestampsOption = false> {
  /** The name of the collection. */
  collection: string

  /**
   * The driver's database, or a function that returns it. The function is called on the first
   * operation, so the model can be defined before the connection is ready.
   */
  db: Db | (() => Db)

  /**
   * The schema of each document as stored: a `z.object`, or a `z.discriminatedUnion` of objects.
   * The `_id` is generated by its `.default()`; without one, the driver generates an `ObjectId`.
   */
  schema: S

  /**
   * Writes `createdAt` when a document is created and `updatedAt` on every write, like Mongoose:
   * `true`, or an object that renames each field or turns it off with `false`. The schema declares
   * them, taking a `Date` and with a `.default()`. Off by default.
   *
   * @example
   *   createdAt: z.union([z.date(), z.iso.datetime().transform((value) => new Date(value))]).default(() => new Date())
   */
  timestamps?: T
}

/**
 * Defines the model of a collection, with the schema as the single source of truth: it validates
 * what is written and types what is read.
 *
 * @example
 *   export const NotesModel = mongozod({
 *     collection: 'notes',
 *     db: () => client.db(),
 *     schema: noteSchema
 *   })
 *
 *   const { document } = await NotesModel.insertOne({ organization, title })
 */
export function mongozod<S extends ModelSchema, const T extends TimestampsOption = false>(
  options: MongozodOptions<S, T> & TimestampsCheck<S, T>
): Model<S, TimestampNamesOf<T>>
// The implementation works with plain documents: the signature above types them with the schema.
export function mongozod(
  options: MongozodOptions<ModelSchema, TimestampsOption>
): Model<ModelSchema> {
  checkFieldNames(options.schema)

  const timestamps = timestampsOf(options.schema, options.timestamps)

  let db: Db | undefined
  let collection: Collection | undefined

  function getDb() {
    db ??= typeof options.db === 'function' ? options.db() : options.db

    return db
  }

  function getCollection() {
    collection ??= getDb().collection(options.collection)

    return collection
  }

  const declaresId = schemaAt(options.schema, '_id', 'filter').length > 0

  /** The options for the driver, without `timestamps`, and the fields the operation stamps. */
  function writeOptions(operationOptions: Document = {}) {
    const { timestamps: stamp, ...driverOptions } = operationOptions

    return { driverOptions, stamps: stamp === false ? {} : timestamps }
  }

  /** Validates a replacement like an insert, keeping the `_id` only when it is given. */
  function parseReplacement(
    filter: Document,
    replacement: Document,
    upsert: unknown,
    stamps: Timestamps,
    now: Date
  ) {
    // An upsert inserts the replacement with the `_id` of the filter, or the server's ObjectId.
    if (
      upsert &&
      declaresId &&
      replacement._id === undefined &&
      !filterEqualities(filter).has('_id')
    ) {
      throw new z.ZodRealError([
        {
          code: 'custom',
          input: filter,
          message:
            'an upsert of a replacement needs the _id in its filter: the server would insert an ObjectId',
          path: ['_id']
        }
      ])
    }

    const document = parseDocument(options.schema, stampDocument(replacement, stamps, now))

    // The `_id` of a document cannot change, so the one a `.default()` generates is dropped, as
    // Mongoose skips it on replacements.
    if (replacement._id === undefined) delete document._id

    return document
  }

  /** Stamps an update and validates it with the schema, given its filter and its options. */
  function parseModelUpdate(
    filter: Document,
    update: unknown,
    updateOptions: Document,
    stamps: Timestamps,
    now: Date
  ) {
    const { arrayFilters, upsert } = updateOptions

    return parseUpdate(options.schema, filter, stampUpdate(update, stamps, now, upsert), {
      arrayFilters,
      upsert
    })
  }

  function aggregate<R extends core.$ZodType>(
    pipeline: readonly Document[],
    aggregateOptions: AggregateOptions & Abortable & { schema: R }
  ): ModelCursor<core.output<R>>
  function aggregate(
    pipeline?: readonly Document[],
    aggregateOptions?: AggregateOptions & Abortable
  ): ModelCursor<Document>
  function aggregate(
    pipeline: readonly Document[] = [],
    aggregateOptions?: AggregateOptions & Abortable & { schema?: core.$ZodType }
  ): ModelCursor<unknown> {
    const { schema, ...driverOptions } = aggregateOptions ?? {}
    const cursor = getCollection().aggregate([...pipeline], driverOptions)

    if (!schema) return new ModelCursor(cursor)

    return new ModelCursor(cursor.map((document) => z.parse(schema, document)))
  }

  // The operations that return documents have several signatures, like the driver's. TypeScript
  // then compares them with the interface's erasing its type parameters, which the projected
  // result depends on.
  function find(): ModelFindCursor<WithId<Document>>
  function find(filter: Document, findOptions?: Document): ModelFindCursor<WithId<Document>>
  function find(filter: Document = {}, findOptions?: Document) {
    return new ModelFindCursor(getCollection().find(filter, findOptions))
  }

  function findOne(): Promise<WithId<Document> | null>
  function findOne(filter: Document, findOptions?: Document): Promise<WithId<Document> | null>
  function findOne(filter: Document = {}, findOptions: Document = {}) {
    return getCollection().findOne(filter, findOptions)
  }

  function findOneAndDelete(
    filter: Document,
    deleteOptions: Document & { includeResultMetadata: true }
  ): Promise<ModifyResult>
  function findOneAndDelete(
    filter: Document,
    deleteOptions?: Document
  ): Promise<WithId<Document> | null>
  function findOneAndDelete(
    filter: Document,
    deleteOptions: Document = {}
  ): Promise<ModifyResult | WithId<Document> | null> {
    return getCollection().findOneAndDelete(filter, deleteOptions)
  }

  function findOneAndReplace(
    filter: Document,
    replacement: Document,
    replaceOptions: Document & { includeResultMetadata: true }
  ): Promise<ModifyResult>
  function findOneAndReplace(
    filter: Document,
    replacement: Document,
    replaceOptions?: Document
  ): Promise<WithId<Document> | null>
  async function findOneAndReplace(
    filter: Document,
    replacement: Document,
    replaceOptions: Document = {}
  ): Promise<ModifyResult | WithId<Document> | null> {
    const { driverOptions, stamps } = writeOptions(replaceOptions)
    const document = parseReplacement(filter, replacement, driverOptions.upsert, stamps, new Date())

    return getCollection().findOneAndReplace(filter, document, driverOptions)
  }

  function findOneAndUpdate(
    filter: Document,
    update: Document,
    updateOptions: Document & { includeResultMetadata: true }
  ): Promise<ModifyResult>
  function findOneAndUpdate(
    filter: Document,
    update: Document,
    updateOptions?: Document
  ): Promise<WithId<Document> | null>
  async function findOneAndUpdate(
    filter: Document,
    update: Document,
    updateOptions: Document = {}
  ): Promise<ModifyResult | WithId<Document> | null> {
    const { driverOptions, stamps } = writeOptions(updateOptions)
    const parsed = parseModelUpdate(filter, update, driverOptions, stamps, new Date())

    return getCollection().findOneAndUpdate(filter, parsed, driverOptions)
  }

  return {
    get collection() {
      return getCollection()
    },
    get db() {
      return getDb()
    },
    name: options.collection,
    schema: options.schema,

    aggregate,

    async bulkWrite(operations: ReadonlyArray<Document>, bulkOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(bulkOptions)
      const now = new Date()

      return getCollection().bulkWrite(
        operations.map((operation): AnyBulkWriteOperation => {
          if ('insertOne' in operation) {
            const document = stampDocument(operation.insertOne.document, stamps, now)

            return { insertOne: { document: parseDocument(options.schema, document) } }
          }

          if ('replaceOne' in operation) {
            const { filter, replacement, upsert } = operation.replaceOne

            return {
              replaceOne: {
                ...operation.replaceOne,
                replacement: parseReplacement(filter, replacement, upsert, stamps, now)
              }
            }
          }

          if ('updateOne' in operation) {
            const { filter, update } = operation.updateOne

            return {
              updateOne: {
                ...operation.updateOne,
                update: parseModelUpdate(filter, update, operation.updateOne, stamps, now)
              }
            }
          }

          if ('updateMany' in operation) {
            const { filter, update } = operation.updateMany

            return {
              updateMany: {
                ...operation.updateMany,
                update: parseModelUpdate(filter, update, operation.updateMany, stamps, now)
              }
            }
          }

          if ('deleteOne' in operation) return { deleteOne: operation.deleteOne }

          return { deleteMany: operation.deleteMany }
        }),
        driverOptions
      )
    },

    countDocuments(filter?: Document, countOptions?: Document) {
      return getCollection().countDocuments(filter, countOptions)
    },

    deleteMany(filter?: Document, deleteOptions?: Document) {
      return getCollection().deleteMany(filter, deleteOptions)
    },

    deleteOne(filter?: Document, deleteOptions?: Document) {
      return getCollection().deleteOne(filter, deleteOptions)
    },

    distinct(key: string, filter: Document = {}, distinctOptions: Document = {}) {
      return getCollection().distinct(key, filter, distinctOptions)
    },

    estimatedDocumentCount(countOptions?: Document) {
      return getCollection().estimatedDocumentCount(countOptions)
    },

    find,
    findOne,
    findOneAndDelete,
    findOneAndReplace,
    findOneAndUpdate,

    async insertMany(inputs: readonly Document[], insertOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(insertOptions)
      const now = new Date()
      const documents = inputs.map((input) =>
        parseDocument(options.schema, stampDocument(input, stamps, now))
      )
      const result = await getCollection().insertMany(documents, driverOptions)

      return {
        ...result,
        // `insertedIds` maps the index of each document to its `_id`, generated or not.
        documents: Object.values(result.insertedIds).map((_id, index) =>
          Object.assign({ _id }, documents[index])
        )
      }
    },

    async insertOne(input: Document, insertOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(insertOptions)
      const document = parseDocument(options.schema, stampDocument(input, stamps, new Date()))
      const result = await getCollection().insertOne(document, driverOptions)

      return { ...result, document: { _id: result.insertedId, ...document } }
    },

    async replaceOne(filter: Document, replacement: Document, replaceOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(replaceOptions)
      const document = parseReplacement(
        filter,
        replacement,
        driverOptions.upsert,
        stamps,
        new Date()
      )

      return getCollection().replaceOne(filter, document, driverOptions)
    },

    async updateMany(filter: Document, update: Document, updateOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(updateOptions)
      const parsed = parseModelUpdate(filter, update, driverOptions, stamps, new Date())

      return getCollection().updateMany(filter, parsed, driverOptions)
    },

    async updateOne(filter: Document, update: Document, updateOptions?: Document) {
      const { driverOptions, stamps } = writeOptions(updateOptions)
      const parsed = parseModelUpdate(filter, update, driverOptions, stamps, new Date())

      return getCollection().updateOne(filter, parsed, driverOptions)
    }
  }
}
